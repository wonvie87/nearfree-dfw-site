export function localizeListing(listing, locale) {
  if (locale !== "en") return listing;
  const translation = LISTING_EN[listing.id];
  if (!translation) return listing;
  const { sourceNotes, ...fields } = translation;
  return {
    ...listing,
    ...fields,
    sources: listing.sources.map((source, index) => ({ ...source, note: sourceNotes[index] || source.note }))
  };
}
